def main() -> int:
    doc = Document(str(DOCX))
    rows = doc.tables[0].rows

    # q_row 模式：可能以 "画像N\n"、"\n"、或直接以题号开头
    q_re = re.compile(r"^(?:画像\s*\d+\s*\n)?\s*(\d+)[、.]\s*")

    rewritten = 0
    for row in rows:
        cell = row.cells[0]
        text = cell.text
        m = q_re.match(text)
        if not m:
            continue
        qno = m.group(1)
        if qno not in REWRITES:
            continue
        prefix = m.group(0)  # "画像1\n1、" 或 "5、"
        cell.text = prefix + REWRITES[qno]
        rewritten += 1

    doc.save(str(DOCX))
    print(f"已改写 {rewritten} 道题 → {DOCX.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())