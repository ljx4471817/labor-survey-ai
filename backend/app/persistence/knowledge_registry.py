_local = threading.local()
_schema_lock = threading.Lock()
_write_lock = threading.Lock()
_schema_ready_for: str | None = None


@contextmanager
def _write_transaction():
    """Serialize registry writes and roll back the whole unit on any error."""
    with _write_lock:
        conn = _get_conn()
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise


def _now() -> str:
    """Return the project's UTC+8 ISO timestamp."""
    return datetime.now(UTC8).isoformat(timespec="seconds")


def _db_target() -> str:
    """Resolve LSX_DB_KB_ADMIN before the optional path override."""
    return os.environ.get("LSX_DB_KB_ADMIN") or str(DB_PATH)


def _get_conn() -> "db.Connection":
    """Lazily create the thread-local registry connection and schema."""
    global _schema_ready_for
    conn = getattr(_local, "conn", None)
    if conn is None:
        target = _db_target()
        conn = db.connect(target)
        if _schema_ready_for != target:
            with _schema_lock:
                if _schema_ready_for != target:
                    conn.executescript(
                        _SCHEMA_PG if conn.backend == "postgres"
                        else _SCHEMA_SQLITE
                    )
                    conn.commit()
                    _schema_ready_for = target
        _local.conn = conn
    return conn


def reset_conn() -> None:
    """Close and clear this thread's connection (tests / target switching)."""
    conn = getattr(_local, "conn", None)
    if conn is not None:
        try:
            conn.close()
        except db.Error:
            pass
        _local.conn = None


def _json(value: Mapping[str, Any] | None) -> str | None:
    if value is None:
        return None
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def _require_text(value: str, label: str) -> str:
    cleaned = str(value or "").strip()
    if not cleaned:
        raise ValueError(f"{label}不能为空")
    return cleaned


def _load_package(conn: "db.Connection", package_id: str) -> dict:
    row = conn.execute(
        "SELECT * FROM kb_packages WHERE id = ?", (package_id,)
    ).fetchone()
    if row is None:
        raise ValueError(f"知识包不存在：{package_id}")
    return dict(row)


def _load_release(conn: "db.Connection", release_id: str) -> dict:
    row = conn.execute(
        "SELECT * FROM kb_releases WHERE id = ?", (release_id,)
    ).fetchone()
    if row is None:
        raise ValueError(f"知识包版本不存在：{release_id}")
    return dict(row)


def _write_audit(
    conn: "db.Connection",
    actor: str,
    action: str,
    target: str,
    before: Mapping[str, Any] | None,
    after: Mapping[str, Any] | None,
) -> None:
    conn.execute(
        "INSERT INTO kb_admin_audit "
        "(actor, action, target, before_json, after_json, created_at) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (actor, action, target, _json(before), _json(after), _now()),
    )


def create_package(
    *,
    package_id: str,
    name: str,
    kind: str,
    created_by: str,
    status: str = "draft",
) -> dict:
    """Create one package and record its audit snapshot."""
    package_id = _require_text(package_id, "知识包 ID")
    name = _require_text(name, "知识包名称")
    created_by = _require_text(created_by, "创建人")
    if kind not in PACKAGE_KINDS:
        raise ValueError(f"未知知识包类型：{kind}")
    if status != "draft":
        raise ValueError("新知识包只能以 draft 状态创建")

    timestamp = _now()
    with _write_transaction() as conn:
        conn.execute(
            "INSERT INTO kb_packages "
            "(id, name, kind, status, current_release_id, created_at, updated_at, created_by, updated_by) "
            "VALUES (?, ?, ?, ?, NULL, ?, ?, ?, ?)",
            (
                package_id, name, kind, status,
                timestamp, timestamp, created_by, created_by,
            ),
        )
        package = _load_package(conn, package_id)
        _write_audit(
            conn, created_by, "create_package",
            f"kb_package:{package_id}", None, package,
        )
        return package


def get_package(package_id: str) -> dict:
    """Return one package snapshot."""
    return _load_package(_get_conn(), package_id)


def list_packages() -> list[dict]:
    """Return all packages in stable package-id order."""
    rows = _get_conn().execute(
        "SELECT * FROM kb_packages ORDER BY kind, id"
    ).fetchall()
    return [dict(row) for row in rows]


def update_package(
    package_id: str,
    *,
    actor: str,
    name: str | None = None,
    status: str | None = None,
) -> dict:
    """Update package display/status fields and audit the before/after state."""
    actor = _require_text(actor, "操作人")
    if status is not None and status not in PACKAGE_STATUSES:
        raise ValueError(f"未知知识包状态：{status}")
    if name is not None and not str(name).strip():
        raise ValueError("知识包名称不能为空")

    if name is None and status is None:
        raise ValueError("请提供要更新的知识包字段")

    with _write_transaction() as conn:
        before = _load_package(conn, package_id)
        if status == "active" and not before["current_release_id"]:
            raise ValueError("知识包没有已发布版本，不能置为 active")
        updates: list[str] = []
        params: list[Any] = []
        if name is not None:
            updates.append("name = ?")
            params.append(str(name).strip())
        if status is not None:
            updates.append("status = ?")
            params.append(status)
        if updates:
            updates.extend(("updated_at = ?", "updated_by = ?"))
            params.extend((_now(), actor, package_id))
            conn.execute(
                f"UPDATE kb_packages SET {', '.join(updates)} WHERE id = ?",
                tuple(params),
            )
        after = _load_package(conn, package_id)
        _write_audit(
            conn, actor, "update_package", f"kb_package:{package_id}", before, after
        )
        return after


def create_release(
    *,
    release_id: str,
    package_id: str,
    version: str,
    artifact_path: str,
    content_hash: str,
    created_by: str,
    based_on_national_release_id: str | None = None,
    build_status: str = "pending",
    eval_status: str = "pending",
) -> dict:
    """Create one immutable release candidate and record its audit snapshot."""
    release_id = validate_release_id(_require_text(release_id, "版本 ID"))
    version = _require_text(version, "版本号")
    artifact_path = _require_text(artifact_path, "制品路径")
    content_hash = _require_text(content_hash, "内容哈希")
    created_by = _require_text(created_by, "创建人")
    if build_status not in RELEASE_BUILD_STATUSES:
        raise ValueError(f"未知构建状态：{build_status}")
    if eval_status not in RELEASE_EVAL_STATUSES:
        raise ValueError(f"未知 Eval 状态：{eval_status}")

    with _write_transaction() as conn:
        package = _load_package(conn, package_id)
        if package["kind"] == "national" and based_on_national_release_id:
            raise ValueError("全国包版本不能基于其他版本")
        if package["kind"] == "provincial" and not based_on_national_release_id:
            raise ValueError("省级包版本必须基于一个全国包版本")
        if based_on_national_release_id:
            basis = _load_release(conn, based_on_national_release_id)
            basis_package = _load_package(conn, basis["package_id"])
            if basis_package["kind"] != "national":
                raise ValueError("省级包版本只能基于全国包版本")
            if basis["id"] == release_id:
                raise ValueError("版本不能基于自身")

        conn.execute(
            "INSERT INTO kb_releases "
            "(id, package_id, version, artifact_path, content_hash, "
            "based_on_national_release_id, build_status, eval_status, "
            "created_at, published_at, created_by) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, NULL, ?)",
            (
                release_id, package_id, version, artifact_path, content_hash,
                based_on_national_release_id, build_status, eval_status,
                _now(), created_by,
            ),
        )
        release = _load_release(conn, release_id)
        _write_audit(
            conn, created_by, "create_release",
            f"kb_release:{release_id}", None, release,
        )
        return release


def get_release(release_id: str) -> dict:
    """Return one release snapshot."""
    return _load_release(_get_conn(), release_id)


def list_releases(package_id: str | None = None) -> list[dict]:
    """Return release snapshots, optionally restricted to one package."""
    conn = _get_conn()
    if package_id:
        rows = conn.execute(
            "SELECT * FROM kb_releases WHERE package_id = ? "
            "ORDER BY created_at, id",
            (package_id,),
        ).fetchall()
    else:
        rows = conn.execute(
            "SELECT * FROM kb_releases ORDER BY created_at, id"
        ).fetchall()
    return [dict(row) for row in rows]


def update_release_status(
    *,
    release_id: str,
    actor: str,
    build_status: str | None = None,
    eval_status: str | None = None,
) -> dict:
    """Update build/Eval gate fields and audit the change."""
    actor = _require_text(actor, "操作人")
    if build_status is not None and build_status not in RELEASE_BUILD_STATUSES:
        raise ValueError(f"未知构建状态：{build_status}")
    if eval_status is not None and eval_status not in RELEASE_EVAL_STATUSES:
        raise ValueError(f"未知 Eval 状态：{eval_status}")

    with _write_transaction() as conn:
        before = _load_release(conn, release_id)
        if before["published_at"]:
            raise ValueError("已发布版本状态不可修改")
        conn.execute(
            "UPDATE kb_releases SET build_status = COALESCE(?, build_status), "
            "eval_status = COALESCE(?, eval_status) WHERE id = ?",
            (build_status, eval_status, release_id),
        )
        after = _load_release(conn, release_id)
        _write_audit(
            conn, actor, "update_release_status",
            f"kb_release:{release_id}", before, after,
        )
        return after


def _validate_publishable(package: dict, release: dict) -> None:
    if release["package_id"] != package["id"]:
        raise ValueError("版本不属于当前知识包")
    if release["build_status"] != "success":
        raise ValueError("只有构建成功的版本才能发布")
    if release["eval_status"] != "passed":
        raise ValueError("只有 Eval 通过的版本才能发布")


def _switch_release(
    *,
    package_id: str,
    release_id: str,
    actor: str,
    action: str,
) -> dict:
    with _write_transaction() as conn:
        before_package = _load_package(conn, package_id)
        release = _load_release(conn, release_id)
        _validate_publishable(before_package, release)
        if before_package["current_release_id"] == release_id:
            if action == "publish_release":
                return before_package
            raise ValueError("该版本已经是当前发布版本")

        published_at = release["published_at"] or _now()
        conn.execute(
            "UPDATE kb_releases SET published_at = ? WHERE id = ?",
            (published_at, release_id),
        )
        conn.execute(
            "UPDATE kb_packages SET current_release_id = ?, status = 'active', "
            "updated_at = ?, updated_by = ? WHERE id = ?",
            (release_id, _now(), actor, package_id),
        )
        after_package = _load_package(conn, package_id)
        _write_audit(
            conn, actor, action, f"kb_package:{package_id}",
            before_package, after_package,
        )
        return after_package


def publish_release(package_id: str, release_id: str, *, actor: str) -> dict:
    """Publish a passed release and move the package current-release pointer.

    本方法只做状态机门禁；产物门禁（manifest + content_hash 绑定）在
    app/services/release_publish.py——它是发布的唯一完整入口。
    """
    return _switch_release(
        package_id=package_id,
        release_id=release_id,
        actor=_require_text(actor, "操作人"),
        action="publish_release",
    )


def rollback_release(package_id: str, release_id: str, *, actor: str) -> dict:
    """Roll the current-release pointer back to another passed release.

    产物门禁同 publish_release：走 app/services/release_publish.py。
    """
    return _switch_release(
        package_id=package_id,
        release_id=release_id,
        actor=_require_text(actor, "操作人"),
        action="rollback_release",
    )


def _load_binding(conn: "db.Connection", province_code: str) -> dict | None:
    row = conn.execute(
        "SELECT * FROM province_kb_bindings WHERE province_code = ?",
        (province_code,),
    ).fetchone()
    return dict(row) if row is not None else None


def bind_province(
    province_code: str,
    package_id: str,
    *,
    actor: str,
) -> dict:
    """Bind or replace one province's provincial knowledge package."""
    province_code = _require_text(province_code, "省级行政区划代码")
    if not province_code.isdigit() or len(province_code) != 6:
        raise ValueError("省级行政区划代码必须为 6 位数字")
    actor = _require_text(actor, "操作人")

    with _write_transaction() as conn:
        before = _load_binding(conn, province_code)
        package = _load_package(conn, package_id)
        if package["kind"] != "provincial":
            raise ValueError("只能绑定省级知识包")
        if package["status"] != "active":
            raise ValueError("只能绑定已发布的省级知识包")

        timestamp = _now()
        if before is None:
            conn.execute(
                "INSERT INTO province_kb_bindings "
                "(province_code, package_id, updated_at, updated_by) "
                "VALUES (?, ?, ?, ?)",
                (province_code, package_id, timestamp, actor),
            )
        else:
            conn.execute(
                "UPDATE province_kb_bindings SET package_id = ?, updated_at = ?, "
                "updated_by = ? WHERE province_code = ?",
                (package_id, timestamp, actor, province_code),
            )
        after = _load_binding(conn, province_code)
        _write_audit(
            conn, actor, "bind_province",
            f"province_kb_binding:{province_code}", before, after,
        )
        return after


def unbind_province(province_code: str, *, actor: str) -> bool:
    """Remove one province binding and audit the removal."""
    province_code = _require_text(province_code, "省级行政区划代码")
    actor = _require_text(actor, "操作人")

    with _write_transaction() as conn:
        before = _load_binding(conn, province_code)
        if before is None:
            return False
        conn.execute(
            "DELETE FROM province_kb_bindings WHERE province_code = ?",
            (province_code,),
        )
        _write_audit(
            conn, actor, "unbind_province",
            f"province_kb_binding:{province_code}", before, None,
        )
        return True


def get_resolution_inputs() -> tuple[list[dict], list[dict], dict[str, str]]:
    """Return package/release/binding snapshots consumed by the pure resolver."""
    with _write_lock:
        conn = _get_conn()
        packages = [
            dict(row)
            for row in conn.execute("SELECT * FROM kb_packages ORDER BY id").fetchall()
        ]
        releases = [
            dict(row)
            for row in conn.execute(
                "SELECT * FROM kb_releases ORDER BY created_at, id"
            ).fetchall()
        ]
        bindings = {
            str(row["province_code"]): str(row["package_id"])
            for row in conn.execute(
                "SELECT province_code, package_id FROM province_kb_bindings"
            ).fetchall()
        }
        return packages, releases, bindings


def list_audit(limit: int = 100) -> list[dict]:
    """Return the newest registry audit entries in chronological order."""
    safe_limit = max(1, min(int(limit), 1000))
    rows = _get_conn().execute(
        "SELECT * FROM kb_admin_audit ORDER BY created_at DESC, id DESC LIMIT ?",
        (safe_limit,),
    ).fetchall()
    return [dict(row) for row in reversed(rows)]
